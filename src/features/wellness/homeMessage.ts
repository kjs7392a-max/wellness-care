const ALL_MESSAGES: readonly string[] = [...HOME_MESSAGES.beforeWork, ...HOME_MESSAGES.afterWork, ...HOME_MESSAGES.holiday];

/** 요일·시간대 → 뽑을 묶음. 주말이 시간보다 먼저다. */
export function homeMessagePool(ctx: HomeMessageContext): readonly string[] {
  if (ctx.dow === 0 || ctx.dow === 6) return HOME_MESSAGES.holiday;
  if (ctx.hour >= 5 && ctx.hour < 11) return HOME_MESSAGES.beforeWork;
  if (ctx.hour >= 18 || ctx.hour < 5) return HOME_MESSAGES.afterWork;
  return ALL_MESSAGES;
}

/** seed ∈ [0,1) 로 묶음에서 하나. 범위 밖 시드는 안쪽으로 접는다(인덱스가 밖으로 나가 undefined 가 그려지지 않게). */
export function pickHomeMessage(ctx: HomeMessageContext, seed: number): string {
  const pool = homeMessagePool(ctx);
  const s = Number.isFinite(seed) ? Math.min(Math.max(seed, 0), 0.999999) : 0;
  return pool[Math.floor(s * pool.length)];
}
