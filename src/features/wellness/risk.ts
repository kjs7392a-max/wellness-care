/** 계절 정보를 프롬프트에 주입한다(원본은 8월 한여름 고정). 현재 월 기준으로 자동 생성. */
export function seasonLine(month: number): string {
  if (month >= 6 && month <= 8) return "- 지금은 한국의 한여름입니다. 덥다는 말은 무더위를 뜻합니다.";
  if (month >= 9 && month <= 11) return "- 지금은 한국의 가을입니다.";
  if (month === 12 || month <= 2) return "- 지금은 한국의 겨울입니다. 춥다는 말은 한파를 뜻할 수 있습니다.";
  return "- 지금은 한국의 봄입니다.";
}
