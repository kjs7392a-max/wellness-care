export const SAFE_ENDINGS = ["죽겠", "죽을 뻔", "죽는 줄", "미치겠", "돌겠", "환장", "죽도록", "죽어라", "죽을 만큼", "죽을 맛"];

/** 0 = 일상/주의(L0/L1), 2 = 위험(L2) */
export function riskLevel(text: string): 0 | 2 {
  const t = (text || "").replace(/\s+/g, " ");
  for (const p of RISK_PHRASES) {
    const i = t.indexOf(p);
    if (i < 0) continue;
    const before = t.slice(Math.max(0, i - 14), i);
    if (SAFE_ENDINGS.some((s) => t.slice(i, i + 8).includes(s))) continue;
    if (IDIOM_CAUSES.some((c) => before.includes(c)) && /(서|어서|아서)\s*$/.test(before)) continue;
    return 2;
  }
  return 0;
}

